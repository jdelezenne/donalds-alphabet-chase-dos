; FUNCTION: DONALD 056A:0342
; kbd_irq9: update key state and queue, then chain to BIOS or acknowledge IRQ1.
; All CSO operands are literal segment offsets, as in the original TASM code.
; DX is the policy word from KBD_DATA:0006; BL is zero for key releases.
kbd_irq9:
    push ax
    push bx
    push cx
    push di
    push ds
    push dx
    push es
    push si

    ; Refresh Caps Lock / Num Lock flags from the BIOS data area.
    and word [cs:CSO(0xf6)], byte -4
    mov ax, 0x40
    mov es, ax
    test byte [es:0x17], 0x40
    je short .check_num_lock
    or word [cs:CSO(0xf6)], 1
.check_num_lock:
    test byte [es:0x17], 0x20
    je short .read_policy
    or word [cs:CSO(0xf6)], 2
.read_policy:
    mov ax, KBD_DATA             ; segment relocation
    mov ds, ax
    mov ax, word [0x6]
    mov word [cs:CSO(0xf4)], ax
    mov dx, word [cs:CSO(0xf4)]
    mov ax, cs
    mov ds, ax
    mov es, ax
    cld
    rr xor, ah, ah
    mov bx, 0x101
    in al, 0x60

    ; E1 starts a three-byte Pause subsequence; E0 marks an extended scan code.
    cmp al, 0xe1
    jne short .check_pause_sequence
    mov byte [cs:CSO(0x182)], 3
.check_pause_sequence:
    cmp byte [cs:CSO(0x182)], 0
    je short .check_extended_prefix
    dec byte [cs:CSO(0x182)]
    test dx, 0x80
    jne short .chain_prefix
    jmp near .acknowledge_irq
.check_extended_prefix:
    cmp al, 0xe0
    jne short .check_release
    mov byte [cs:CSO(0x181)], 1
.chain_prefix:
    jmp near .chain_bios
.check_release:
    test al, 0x80
    je short .translate_scan_code
    rr xor, bl, bl
    and al, 0x7f
.translate_scan_code:
    cmp byte [cs:CSO(0x181)], 0
    je short .translate_normal
    mov byte [cs:CSO(0x181)], 0
    mov byte [cs:CSO(0x55e)], 1
    mov di, CSO(0x40)
    mov cx, 0x11
    repne scasb
    mov al, byte [di + 0xf]
    rr or, cx, cx
    jne short .update_key_state
    mov byte [cs:CSO(0x55e)], 0
    jmp near .acknowledge_irq
.translate_normal:
    rr mov, di, ax
    mov al, byte [cs:di + CSO(0xf8)]
.update_key_state:
    ; Save the translation-table position and update the pressed-key bitmap.
    mov word [cs:CSO(0x55f)], di
    rr mov, di, ax
    shr di, 1
    shr di, 1
    shr di, 1
    rr mov, cl, al
    and cl, 7
    shl bl, cl
    shl bh, cl
    not bh
    mov cl, byte [cs:di + CSO(0x171)]
    rr and, cl, bl
    and byte [cs:di + CSO(0x171)], bh
    or byte [cs:di + CSO(0x171)], bl

    ; Pack Ctrl, Alt and Shift into AH, alongside the translated key in AL.
    test byte [cs:CSO(0x178)], 4
    jne short .set_ctrl
    test byte [cs:CSO(0x179)], 1
    je short .check_alt
.set_ctrl:
    or ah, 2
.check_alt:
    test byte [cs:CSO(0x178)], 0x50
    je short .check_extended_translation
    or ah, 4
.check_extended_translation:
    cmp byte [cs:CSO(0x55e)], 0
    je short .check_shift
    mov byte [cs:CSO(0x55e)], 0
    test dx, 2
    jne short .check_shift
    mov si, word [cs:CSO(0x55f)]
    mov al, byte [si + 0x1f]
    cmp si, 0x21
    jge short .check_repeat
.check_shift:
    test byte [cs:CSO(0x176)], 0x10
    jne short .set_shift
    test byte [cs:CSO(0x178)], 2
    je short .check_caps_lock
.set_shift:
    or ah, 1
.check_caps_lock:
    test word [cs:CSO(0xf6)], 1
    je short .check_num_lock_translation
    test byte [cs:di + CSO(0x151)], ch
    je short .check_num_lock_translation
    xor ah, 1
.check_num_lock_translation:
    test word [cs:CSO(0xf6)], 2
    je short .check_repeat
    test byte [cs:di + CSO(0x161)], ch
    je short .check_repeat
    xor ah, 1
.check_repeat:
    test dx, 1
    jne short .check_ctrl_alt_delete
    rr or, cl, cl
    je short .check_ctrl_alt_delete
    jmp near .acknowledge_irq
.check_ctrl_alt_delete:
    cmp ax, 0x668
    je short .chain_special_key
    cmp ax, 0x64c
    jne short .queue_key_press
.chain_special_key:
    jmp short .chain_bios
    nop
.queue_key_press:
    rr or, bl, bl
    je short .chain_bios
    mov di, word [cs:CSO(0xf2)]
    rr mov, si, di
    add di, 2
    and di, 0x7f
    cmp di, word [cs:CSO(0xf0)]
    je short .check_special_keys
    ; Keep the original 16-bit displacement even when it fits in eight bits.
    mov word [cs:word si + CSO(0x70)], ax
    mov word [cs:CSO(0xf2)], di
.check_special_keys:
    mov di, CSO(0x18b)
    mov cx, 9
    repne scasb
    rr or, cx, cx
    jne short .chain_bios
    cmp ax, 0x220
    je short .toggle_control_flag
    cmp ax, 0x320
    jne short .check_escape_callback
.toggle_control_flag:
    push ds
    push ax
    mov ax, KBD_DATA             ; segment relocation
    mov ds, ax
    xor word [0x4], 1
    pop ax
    pop ds
.check_escape_callback:
    cmp al, 0x6e
    jne short .check_bios_policy
    cmp word [cs:CSO(0x3e)], 0
    je short .check_bios_policy
    call far [cs:CSO(0x3c)]
.check_bios_policy:
    ; Look for a per-key policy mask before applying the default chain bit.
    mov di, CSO(0x8)
    mov cx, 0x1c
    shr cx, 1
    repne scasw
    rr or, cx, cx
    je short .check_default_policy
    mov bx, word [di + 0x18]
    rr and, bx, dx
    jne short .chain_bios
    jmp short .acknowledge_irq
    nop
.check_default_policy:
    test dx, 4
    je short .acknowledge_irq
.chain_bios:
    ; The BIOS handler owns acknowledgement when this path is selected.
    pop si
    pop es
    pop dx
    pop ds
    pop di
    pop cx
    pop bx
    pop ax
    sti
    jmp far [cs:CSO(0x183)]
.acknowledge_irq:
    ; Pulse the keyboard controller, clear the BIOS E0 flag, then send PIC EOI.
    in al, 0x61
    rr mov, ah, al
    or al, 0x80
    out 0x61, al
    xchg al, ah
    out 0x61, al
    mov ax, 0x40
    mov es, ax
    mov al, byte [es:0x96]
    and al, 0xfd
    mov byte [es:0x96], al
    mov al, 0x20
    out 0x20, al
    pop si
    pop es
    pop dx
    pop ds
    pop di
    pop cx
    pop bx
    pop ax
    iret

