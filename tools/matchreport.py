#!/usr/bin/env python3
"""Write docs/STATUS.md from config/retail/symbols.csv (status: matched|nonmatching|asm|lib|todo)."""
import csv, collections
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader(open(ROOT / "config/retail/symbols.csv")))
tot = collections.Counter(); by = collections.Counter()
for r in rows:
    n = int(r["size"] or 0, 0) if r["size"] else 0; tot[r["status"]] += n; by[r["status"]] += 1
allb = sum(tot.values()) or 1
out = ["# Status", "", "Generated by `tools/matchreport.py`. Do not edit by hand.", "",
       "| status | functions | bytes | % bytes |", "|---|---|---|---|"]
out += [f"| {k} | {by[k]} | {tot[k]} | {100*tot[k]/allb:.2f} |" for k in sorted(by)]
summ = ROOT / "build/summary.txt"
if summ.exists(): out += ["", "**verify.py:** " + summ.read_text().strip()]
import re
asm = []
for a in sorted((ROOT / "src/asm").glob("*.asm")):
    t = a.read_text(); m = re.search(r"SEGMENT:\s*DONALD\s+(\w{4})\s+(\w{4})-(\w{4})", t)
    if m: asm.append(f"| {a.relative_to(ROOT)} | {m.group(1)}:{m.group(2)}-{m.group(3)} | {int(m.group(3),16)-int(m.group(2),16)} | {t.count('; FUNCTION:')} | {sum(1 for l in t.splitlines() if l.startswith('    db') and '; ' in l)} |")
if asm: out += ["", "Assembly modules (NASM, byte-exact; checked by verify.py):", "", "| file | range | bytes | functions | instructions kept as db |", "|---|---|---|---|---|"] + asm
out += ["", "| name | addr | size | status | notes |", "|---|---|---|---|---|"]
out += [f"| {r['name']} | {r['addr']} | {r['size']} | {r['status']} | {r['notes']} |" for r in rows]
(ROOT / "docs/STATUS.md").write_text("\n".join(out) + "\n"); print("\n".join(out[:8 + len(by)]))
