#!/usr/bin/env python3
"""Summarise recorded symbols and source declarations. Does not build or verify anything."""
import collections
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader(open(ROOT / "config/retail/symbols.csv")))
covered = collections.defaultdict(set); by = collections.Counter()
for r in rows:
    n = int(r["size"] or 0, 0) if r["size"] else 0
    start = int(r["addr"][:4], 16) * 16 + int(r["addr"][5:], 16)
    covered[r["status"]].update(range(start, start + n)); by[r["status"]] += 1
tot = {status: len(points) for status, points in covered.items()}
out = ["# Status", "", "Generated by `tools/matchreport.py`. Do not edit by hand.", "",
       "These are recorded classifications and match results, not a fresh build or verification. "
       "Assembly function body ranges exclude embedded data; overlapping assembly helper bodies are counted once. "
       "These totals are not whole-image coverage percentages. A whole-executable comparison is required to prove "
       "resolved calls, data references, layout, and file identity.", "",
       "| status | records | unique catalogued bytes |", "|---|---|---|"]
out += [f"| {k} | {by[k]} | {tot[k]} |" for k in sorted(by)]
summ = ROOT / "build/summary.txt"
if summ.exists():
    out += ["", "**Saved verifier summary (may predate source changes):** " + summ.read_text().strip()]


data_rows = list(csv.DictReader(open(ROOT / "config/retail/asm_data.csv")))

asm = []
for a in sorted((ROOT / "src").rglob("*.asm")):
    t = a.read_text()
    m = re.search(r"SEGMENT:\s*DONALD\s+(\w{4})\s+(\w{4})-(\w{4})", t)
    if m:
        objects = [r for r in data_rows if r["source"] == a.relative_to(ROOT).as_posix()]
        code_data = sum(int(r["size"]) for r in objects if re.fullmatch(r"[0-9A-Fa-f]{4}", r["segment"]))
        far_data = sum(int(r["size"]) for r in objects if not re.fullmatch(r"[0-9A-Fa-f]{4}", r["segment"]))
        asm.append(f"| {a.relative_to(ROOT)} | {m.group(1)}:{m.group(2)}-{m.group(3)} | "
                   f"{int(m.group(3),16)-int(m.group(2),16)} | {t.count('; FUNCTION:')} | "
                   f"{code_data} | {far_data} |")
if asm:
    out += ["", "Assembly source inventory (not a comparison result):", "",
            "The module's CODE span includes routines, explicitly catalogued data and alignment NOPs. "
            "DATA bytes are additional far-data storage, outside that CODE span.", "",
            "| file | declared CODE range | span bytes | routine annotations | CODE data bytes | DATA bytes |",
            "|---|---|---|---|---|---|"] + asm
data_counts = collections.Counter(); data_bytes = collections.defaultdict(set)
for r in data_rows:
    data_counts[r["segment"]] += 1
    start = int(r["offset"], 16)
    data_bytes[r["segment"]].update(range(start, start + int(r["size"])))
out += ["", "Assembly data inventory (owned storage only; aliases do not add bytes):", "",
        "See `config/retail/asm_data.csv` for every object, type, boundary and access evidence, and "
        "`config/retail/asm_functions.csv` for callable entries and shared-body notes. "
        "`tools/asm_inventory.py` checks real assembled bounds; this report only summarizes the catalogs.", "",
        "| address space | objects | initialized bytes |", "|---|---|---|"]
out += [f"| {space} | {data_counts[space]} | {len(data_bytes[space])} |" for space in sorted(data_counts)]
out += ["", "| name | addr | size | recorded status | notes |", "|---|---|---|---|---|"]
out += [f"| {r['name']} | {r['addr']} | {r['size']} | {r['status']} | {r['notes']} |" for r in rows]
(ROOT / "docs/STATUS.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:8 + len(by)]))
