#!/usr/bin/env python3
"""Summarise recorded symbols and source declarations. Does not build or verify anything."""
import collections
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader(open(ROOT / "config/retail/symbols.csv")))
tot = collections.Counter(); by = collections.Counter()
for r in rows:
    n = int(r["size"] or 0, 0) if r["size"] else 0
    tot[r["status"]] += n; by[r["status"]] += 1
allb = sum(tot.values()) or 1
out = ["# Status", "", "Generated by `tools/matchreport.py`. Do not edit by hand.", "",
       "These are recorded classifications and match results, not a fresh build or verification. "
       "Assembly module spans include embedded data. A whole-executable comparison is required to prove "
       "resolved calls, data references, layout, and file identity.", "",
       "| status | records | bytes | % bytes |", "|---|---|---|---|"]
out += [f"| {k} | {by[k]} | {tot[k]} | {100*tot[k]/allb:.2f} |" for k in sorted(by)]
summ = ROOT / "build/summary.txt"
if summ.exists():
    out += ["", "**Saved verifier summary (may predate source changes):** " + summ.read_text().strip()]


def db_counts(source):
    """Do not assume unclassified CODE bytes are data or silently exclude opaque instruction blobs.

    A CODE segment may also contain tables, state, and alignment. The mnemonic-comment convention
    identifies the documented single-instruction encoding exceptions; it does not verify them.
    """
    classes = {}; current = None
    counts = {"data": 0, "nop": 0, "instruction": 0, "other": 0}
    instruction_comment = re.compile(r";\s*(?:mov|rcl|rcr|add|adc|sub|sbb|and|or|xor|cmp|test|"
                                     r"push|pop|call|jmp|ret|retf|iret|in|out|xchg|shl|shr|sar)\b", re.I)
    for line in source.splitlines():
        segment = re.match(r"\s*segment\s+(\S+)(.*)", line, re.I)
        if segment:
            current = segment.group(1)
            kind = re.search(r"\bclass=(\w+)", segment.group(2), re.I)
            if kind: classes[current] = kind.group(1).upper()
        if not re.match(r"\s*db\s+", line, re.I): continue
        if classes.get(current) == "DATA": counts["data"] += 1
        elif re.match(r"\s*db\s+0x90\s*(?:;.*)?$", line, re.I): counts["nop"] += 1
        elif instruction_comment.search(line): counts["instruction"] += 1
        else: counts["other"] += 1
    return counts


asm = []
for a in sorted((ROOT / "src/asm").glob("*.asm")):
    t = a.read_text()
    m = re.search(r"SEGMENT:\s*DONALD\s+(\w{4})\s+(\w{4})-(\w{4})", t)
    if m:
        db = db_counts(t)
        asm.append(f"| {a.relative_to(ROOT)} | {m.group(1)}:{m.group(2)}-{m.group(3)} | "
                   f"{int(m.group(3),16)-int(m.group(2),16)} | {t.count('; FUNCTION:')} | "
                   f"{db['instruction']} | {db['nop']} | {db['other']} | {db['data']} |")
if asm:
    out += ["", "Assembly source inventory (not a comparison result):", "",
            "`db` counts are source directives, not instruction or byte counts. Other CODE `db` includes "
            "embedded tables/state and any opaque instruction bytes; a comment alone is not verification.", "",
            "| file | declared range | span bytes | annotations | mnemonic-comment db | NOP db | other CODE db | DATA db |",
            "|---|---|---|---|---|---|---|---|---|"] + asm
out += ["", "| name | addr | size | recorded status | notes |", "|---|---|---|---|---|"]
out += [f"| {r['name']} | {r['addr']} | {r['size']} | {r['status']} | {r['notes']} |" for r in rows]
(ROOT / "docs/STATUS.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:8 + len(by)]))
